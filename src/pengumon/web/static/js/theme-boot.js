// This browser's theme, on <html> before the page is drawn: a classic script in <head> (no module, no import), so it
// runs before the first paint and the page never flashes the wrong theme (docs/themes.md, "How the page applies a theme").
//
// The server writes the default theme (Settings > Display) as <html data-look> and data-look-default, and the themes
// it has as data-looks ([{id, modes, css, ...}]). This browser's own choices, made in the header's theme menu (js/themes.js),
// are in localStorage: `pengumon.look` (a theme id; none: the default) and `pengumon.theme` (light or dark; none: the
// system's). A theme with one mode forces it.
//
// The script sits after the page's own stylesheets: it writes the link to the theme's stylesheet (`css`: its tokens,
// skin and card views' styles, generated by the server) where it stands, so the browser waits for that sheet before the
// first paint as for the others, and only the theme in use is loaded. js/themes.js links another one on a switch.
(function () {
  var root = document.documentElement;
  var read = function (key) {
    try { return localStorage.getItem(key) || ''; } catch (e) { return ''; }
  };
  var looks = [];
  try { looks = JSON.parse(root.getAttribute('data-looks') || '[]'); } catch (e) { looks = []; }
  var find = function (id) {
    for (var i = 0; i < looks.length; i++) if (looks[i] && looks[i].id === id) return looks[i];
    return null;
  };
  // a theme's files are ours, under /static/v/<version>/themes/ (pengumon.web.themes.page_list): anything else in the
  // list is never linked
  var ours = function (url) {
    return typeof url === 'string' && /^\/static\/v\/[\w-]+\/themes\/[\w-]+\/(?:[\w-]+\/)*[\w-]+\.(?:css|js)$/.test(url);
  };
  var look = find(read('pengumon.look')) || find(root.getAttribute('data-look-default')) || find('default');
  if (!look) return;
  root.setAttribute('data-look', look.id);
  var mode = read('pengumon.theme');
  if (look.modes && look.modes.length === 1) root.setAttribute('data-theme', look.modes[0]);
  else if (mode === 'light' || mode === 'dark') root.setAttribute('data-theme', mode);
  else root.removeAttribute('data-theme');
  if (ours(look.css)) {
    // written by the parser, not appended: a parser-made stylesheet holds the first paint until it is loaded
    var link = document.createElement('link');
    link.rel = 'stylesheet';
    link.href = look.css;
    link.setAttribute('data-look-css', look.id);
    document.write(link.outerHTML);
  }
  // the theme's own views of cards (docs/themes.md, "Drawing a card"): fetched now, so they are there when the cards mount
  var views = look.views || {};
  for (var panel in views) {
    if (!Object.prototype.hasOwnProperty.call(views, panel) || !ours(views[panel])) continue;
    var pre = document.createElement('link');
    pre.rel = 'modulepreload';
    pre.href = views[panel];
    document.head.appendChild(pre);
  }
})();
