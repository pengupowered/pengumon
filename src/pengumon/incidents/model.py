"""An incident and the classifier's overall diagnosis."""

from datetime import datetime
from typing import List, Literal, Optional

from pydantic import BaseModel, Field, computed_field, field_validator

from pengumon.incidents.taxonomy import CauseCode, current_cause, incident_cause
from pengumon.models.probes import PathTraceHop


SeverityType = Literal["info", "warning", "critical"]
# busy: delay explained by heavy line load; unknown: nothing is measured (this host cannot send pings)
StatusCode = Literal["healthy", "busy", "degraded", "down", "unknown"]

# A line cannot carry much more than its capacity, so a load beyond this is a bad reading (a router counter that jumped
# when the line dropped), not traffic: engine.load leaves such samples out, and an incident recorded with one before
# that was fixed is flagged `load_suspect`.
LOAD_IMPLAUSIBLE_PCT = 150.0


class Incident(BaseModel):
    """An identified network incident / outage event."""
    id: Optional[int] = None
    start_time: float
    end_time: Optional[float] = None
    duration_seconds: Optional[float] = None
    cause_code: CauseCode

    @field_validator("cause_code")
    @classmethod
    def _current_cause(cls, v: str) -> str:
        return current_cause(v)
    title: str
    description: str
    severity: SeverityType
    affected_targets: List[str] = Field(default_factory=list)
    resolved: bool = False
    path_trace: Optional[List[PathTraceHop]] = None
    load_pct: Optional[float] = None  # peak WAN load around the incident, % of line capacity
    expected: bool = False  # explained by load (bufferbloat), not a fault
    # IncidentKind; None only for rows never classified, which schema v6 backfills. Deliberately a plain string:
    # a row with an unknown value (written by a newer build, or edited by hand) must not break the API.
    kind: Optional[str] = None
    # How long probes were lost (incidents.loss): from the first lost probe of the affected targets to the last, plus one
    # probe interval. start_time / end_time are detection times, a few seconds late on both ends. None: not known (open,
    # or its raw samples were gone before it was computed); loss_seconds 0: no probe was lost (raised on latency).
    loss_start: Optional[float] = None
    loss_seconds: Optional[float] = None
    # The outage this incident belongs to (incidents.outages): the id of the outage's first incident. None: not
    # groupable (load, unknown, a host app, expected), and everywhere but GET /api/incidents and the MCP tool, which fill it.
    outage_id: Optional[int] = None

    @computed_field
    @property
    def load_suspect(self) -> bool:
        """load_pct is more than a line can carry (LOAD_IMPLAUSIBLE_PCT): do not show it as a figure."""
        return self.load_pct is not None and self.load_pct > LOAD_IMPLAUSIBLE_PCT

    @computed_field
    @property
    def cause(self) -> str:
        """The cause category for the timeline lanes (CAUSE_CATEGORIES), derived from kind and cause_code (and, for an
        older isp_outage, its description: incidents.taxonomy.incident_cause)."""
        return incident_cause(self.kind, self.cause_code, self.description)


class SystemDiagnosis(BaseModel):
    """Overall system diagnosis generated by the classifier."""
    status: StatusCode = "healthy"
    cause_code: CauseCode = "nominal"

    @field_validator("cause_code")
    @classmethod
    def _current_cause(cls, v: str) -> str:
        return current_cause(v)
    title: str = "All Network Hops Operational"
    description: str = "Latency and packet loss across local mesh, gateway, and internet hops are within normal thresholds."
    active_incident: Optional[Incident] = None
    timestamp: float = Field(default_factory=lambda: datetime.now().timestamp())
    load_pct: Optional[float] = None  # current WAN load, % of line capacity; None without fresh router data
